/** Metin; {ad} yer tutucuları doldurulur (değerler çağıran tarafından gerekiyorsa kaçışlanır) */
export function t(key, vars = {}) {
  const text = DICT[LANG][key] ?? DICT.tr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : ""));
}

/** "20:00" → Türkçe "20.00", İngilizce "20:00" */
export const formatTime = (hhmm) => {
  const [h = "", m = ""] = String(hhmm).split(":");
  return t("time", { h, m });
};

